import {
  AvailabilityNotice,
  Capabilities,
  type FetchSource,
  PatinaProvider,
  PromptInput,
  ProposalPreview,
  RedoButton,
  ResetButton,
  SkippedNotice,
  Surface,
  SurfaceMessage,
  UndoButton,
  useSurface,
} from "@patina-ui/react";
import { type ReactNode, useCallback, useEffect, useState } from "react";
import { PatinaChart, PatinaStat, PatinaTable } from "../patina/blocks.js";
import { Chart } from "./components/Chart.js";
import { DataTable } from "./components/DataTable.js";
import { FilterBar } from "./components/FilterBar.js";
import { DashboardLayout, StatRow } from "./components/Layout.js";
import { StatCard } from "./components/StatCard.js";
import { FiltersProvider, useFilters } from "./data.js";

const SURFACE = "clinic.dashboard";

/** Host components, by the names used in the manifest. */
const components = {
  DashboardLayout,
  StatRow,
  StatCard,
  FilterBar,
  Chart,
  DataTable,
  // Data blocks generated by `patina scan` in the app's own style.
  PatinaTable,
  PatinaChart,
  PatinaStat,
};

const EXAMPLES = [
  "Hide the revenue column and move status after date",
  "Put the appointments table above the chart",
  "Default the filter to this week",
  "Add a no-shows card",
  "Add a bar chart of revenue by vet",
  "Show the owner column",
  "Show me other users' appointments",
];

interface User {
  userId: string;
  name: string;
}

export function App() {
  return (
    <FiltersProvider>
      <DataProvider>
        <div className="app">
          <Header />
          <Customizer />
          <main>
            <Surface
              id={SURFACE}
              components={components}
              fallback={<p className="muted">Loading dashboard…</p>}
            />
          </main>
        </div>
      </DataProvider>
    </FiltersProvider>
  );
}

/**
 * Data blocks load catalog sources through the app's own endpoints. The catalog binds their
 * params to the saved filter defaults; here the live filter values take precedence.
 */
function DataProvider({ children }: { children: ReactNode }) {
  const { filters } = useFilters();
  const fetchSource = useCallback<FetchSource>(
    async ({ path, params, signal }) => {
      const qs = new URLSearchParams({ ...params, range: filters.range, status: filters.status });
      const res = await fetch(`${path}?${qs}`, { signal });
      if (!res.ok) throw new Error(`Couldn't load data (${res.status})`);
      return res.json();
    },
    [filters.range, filters.status],
  );
  return (
    <PatinaProvider endpoint="/api/patina" fetchSource={fetchSource}>
      {children}
    </PatinaProvider>
  );
}

/** For the demo's "staff" user: the insights report of what customers asked for. */
function InsightsPanel() {
  const [report, setReport] = useState<string | null>(null);
  const load = async () => {
    const res = await fetch("/api/patina/insights?format=markdown&since=30d");
    setReport(res.ok ? await res.text() : `Couldn't load insights (${res.status}).`);
  };
  return (
    <details
      className="insights"
      onToggle={(e) => (e.currentTarget.open ? void load() : undefined)}
    >
      <summary>Insights: what customers asked for</summary>
      <pre>{report ?? "Loading…"}</pre>
    </details>
  );
}

function Header() {
  const [me, setMe] = useState<{ user: User; users: User[] } | null>(null);
  useEffect(() => {
    fetch("/api/me")
      .then((r) => r.json())
      .then(setMe);
  }, []);
  const switchUser = async (userId: string) => {
    await fetch("/api/me", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ userId }),
    });
    window.location.reload();
  };
  return (
    <header className="header">
      <div>
        <div className="brand">Happy Paws Veterinary</div>
        <div className="muted">Clinic dashboard · Patina demo</div>
      </div>
      {me?.user.userId === "alice" && <InsightsPanel />}
      {me && (
        <label className="user-switch">
          Signed in as
          <select value={me.user.userId} onChange={(e) => void switchUser(e.target.value)}>
            {me.users.map((u) => (
              <option key={u.userId} value={u.userId}>
                {u.name}
              </option>
            ))}
          </select>
        </label>
      )}
    </header>
  );
}

/** Built entirely from Patina's headless primitives, styled by the host. */
function Customizer() {
  const s = useSurface(SURFACE);
  return (
    <section
      className={`customizer${s.proposal ? " has-proposal" : ""}`}
      aria-label="Customize this dashboard"
    >
      <PromptInput surfaceId={SURFACE}>
        {({ formProps, inputProps, value, busy, setValue }) => (
          <form className="prompt" {...formProps}>
            <span className="sparkle" aria-hidden>
              ✦
            </span>
            <input
              {...inputProps}
              placeholder="Customize this dashboard, e.g. “hide the revenue column”"
              autoComplete="off"
            />
            <button type="submit" className="primary" disabled={busy || !value.trim()}>
              {s.status === "proposing" ? "Thinking…" : "Preview"}
            </button>
            <div className="examples">
              {EXAMPLES.map((ex) => (
                <button
                  key={ex}
                  type="button"
                  className="chip"
                  onClick={() => setValue(ex)}
                  disabled={busy}
                >
                  {ex}
                </button>
              ))}
            </div>
          </form>
        )}
      </PromptInput>

      <AvailabilityNotice surfaceId={SURFACE}>
        {(a) => <p className="message message-availability">{a.message}</p>}
      </AvailabilityNotice>

      <SurfaceMessage surfaceId={SURFACE}>
        {(m, { pick }) => {
          // Answers to "what can I …?" come as a lead line and a list.
          const [lead, ...items] = m.text.split("\n");
          return (
            <div
              className={`message message-${m.kind}`}
              role={m.kind === "error" ? "alert" : "status"}
            >
              <p>{lead}</p>
              {items.length > 0 && (
                <ul>
                  {items.map((line) => (
                    <li key={line}>{line.replace(/^- /, "")}</li>
                  ))}
                </ul>
              )}
              {/* A clarifying question's choices: each one is possible. */}
              {m.options?.map((o) => (
                <button key={o.label} type="button" onClick={() => pick(o.label)}>
                  {o.label}
                </button>
              ))}
            </div>
          );
        }}
      </SurfaceMessage>

      <ProposalPreview surfaceId={SURFACE}>
        {({ changes, commit, discard, busy }) => (
          <div className="preview" aria-live="polite">
            <div className="preview-title">Preview: the dashboard below shows these changes</div>
            <ul>
              {changes.map((c) => (
                <li key={c.opIndex}>{c.text}</li>
              ))}
            </ul>
            <div className="actions">
              <button type="button" className="primary" onClick={commit} disabled={busy}>
                Apply
              </button>
              <button type="button" onClick={discard} disabled={busy}>
                Discard
              </button>
            </div>
          </div>
        )}
      </ProposalPreview>

      <div className="toolbar">
        <UndoButton surfaceId={SURFACE}>Undo</UndoButton>
        <RedoButton surfaceId={SURFACE}>Redo</RedoButton>
        <ResetButton surfaceId={SURFACE}>Reset to default</ResetButton>
        <SkippedNotice surfaceId={SURFACE} className="skipped" />
      </div>

      {/* Built from this user's manifest and catalog: Bob (no finance access) sees no revenue. */}
      <Capabilities surfaceId={SURFACE} className="capabilities" />
    </section>
  );
}

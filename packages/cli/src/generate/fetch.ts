import type { ScannedSource, ScanResult } from "../scan/types.js";

const q = (s: string) => JSON.stringify(s);

function sourceOptions(s: ScannedSource): string[] {
  const lines: string[] = [];
  if (s.rows) lines.push(`rows: ${q(s.rows)},`);
  const p = s.paging;
  if (p?.style === "offset")
    lines.push(
      `paging: { style: "offset", size: 200, limit: ${q(p.limit)}, offset: ${q(p.offset)} }, // TODO: the endpoint's max page size`,
    );
  if (p?.style === "page")
    lines.push(
      `paging: { style: "page", size: 100, page: ${q(p.page)}, pageSize: ${q(p.pageSize)} }, // TODO: the endpoint's max page size`,
    );
  if (p?.style === "cursor")
    lines.push(
      `paging: { style: "cursor", cursor: ${q(p.cursor)}, next: "nextCursor" }, // TODO: where the response puts the next cursor`,
    );
  if (s.dateRange)
    lines.push(
      `dateRange: { from: ${q(s.dateRange.from)}, to: ${q(s.dateRange.to)} }, // format: "date" for YYYY-MM-DD`,
    );
  return lines;
}

/**
 * A draft `fetchSource` for the provider, from what the scan saw: envelopes, paging, date
 * ranges and tenant placeholders. Pass it to `<PatinaProvider fetchSource={…}>`.
 */
export function renderFetch(scan: ScanResult): string {
  const tenant = [...new Set(Object.values(scan.sources).flatMap((s) => s.pathParams ?? []))];
  const perSource = Object.entries(scan.sources)
    .filter(([, s]) => Object.keys(s.fields).length > 0)
    .map(([id, s]) => [id, sourceOptions(s)] as const)
    .filter(([, lines]) => lines.length > 0);
  const args = tenant.length
    ? `{ ${tenant.join(", ")} }: { ${tenant.map((t) => `${t}: string`).join("; ")} }`
    : "";
  const out = [
    "// Generated by `patina scan`: how data blocks fetch your catalog's sources. Review it, then",
    "// pass it to <PatinaProvider fetchSource={…}>. With paging, every page is fetched, so the",
    "// source can be `complete: true` in the catalog.",
    'import { createFetchSource } from "@patina-ui/react";',
    "",
    `export const appFetchSource = (${args}) =>`,
    "  createFetchSource({",
    '    // baseUrl: import.meta.env.VITE_API_URL, credentials: "include", // when the API is on another origin',
    ...(tenant.length
      ? [
          `    params: { ${tenant.join(", ")} }, // fills ${tenant.map((t) => `:${t}`).join(", ")} in paths`,
        ]
      : []),
  ];
  if (perSource.length) {
    out.push("    sources: {");
    for (const [id, lines] of perSource) {
      out.push(`      ${id}: {`);
      for (const l of lines) out.push(`        ${l}`);
      out.push("      },");
    }
    out.push("    },");
  }
  out.push("  });", "");
  return out.join("\n");
}

import type { ScannedField, ScanResult } from "../scan/types.js";

const HEADER = `// Generated by \`patina scan\` as a starting point. Review it before committing:
//  - Remove sources users shouldn't build views from.
//  - Check field kinds and labels; mark anything personal as \`sensitive: true\`.
//  - Bind query params to page state (e.g. range: { from: "filters.dateRange" }).
//  - Set \`complete: true\` only for endpoints that return ALL matching rows (not one page);
//    Patina only offers totals and averages for those.
// Re-running \`patina scan\` won't overwrite this file (it writes catalog.draft.ts instead).
`;

const q = (s: string) => JSON.stringify(s);

export function humanLabel(id: string): string {
  const spaced = id
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .toLowerCase()
    .trim();
  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}

function renderField(name: string, f: ScannedField): string {
  const opts = [`label: ${q(humanLabel(name))}`, ...(f.sensitive ? ["sensitive: true"] : [])].join(
    ", ",
  );
  switch (f.kind) {
    case "enum":
      return `f.enum([${(f.values ?? []).map(q).join(", ")}], { ${opts} })`;
    case "currency":
      return `f.currency("USD", { ${opts} }) /* TODO: currency code */`;
    default:
      return `f.${f.kind}({ ${opts} })`;
  }
}

export function renderCatalog(scan: ScanResult): string {
  const lines: string[] = [
    HEADER,
    `import { defineCatalog, f } from "@patina-ui/core";`,
    "",
    "export const catalog = defineCatalog({",
  ];
  const todo: string[] = [];
  for (const [id, s] of Object.entries(scan.sources)) {
    const fields = Object.entries(s.fields);
    if (fields.length === 0) {
      todo.push(
        `  // TODO ${s.endpoint.path}: couldn't determine the shape of its rows (${s.evidence.join(", ")}).`,
      );
      continue;
    }
    lines.push(`  ${id}: {`);
    lines.push(`    label: ${q(humanLabel(id))},`);
    lines.push(`    // Found in: ${s.evidence.join(", ")}`);
    lines.push(`    endpoint: { path: ${q(s.endpoint.path)}, method: "GET" },`);
    if (s.params.length) {
      lines.push(`    params: {`);
      for (const p of s.params) lines.push(`      // ${p}: { from: "<nodeId>.<prop>" },`);
      lines.push(`    },`);
    }
    lines.push(`    complete: false, // TODO: true if the endpoint returns all matching rows`);
    if (s.fields.id) lines.push(`    rowKey: "id",`);
    lines.push(`    fields: {`);
    for (const [name, f] of fields) lines.push(`      ${name}: ${renderField(name, f)},`);
    lines.push(`    },`);
    lines.push(`  },`);
  }
  lines.push(...todo, "});", "");
  return lines.join("\n");
}
